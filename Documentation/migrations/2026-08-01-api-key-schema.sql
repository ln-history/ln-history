-- ============================================================================
-- Migration: `api` schema for multi-tenant API keys + cost-based rate limiting
-- Date:      2026-08-01
-- Role:      admin (owner of the schema; the API connects as admin)
-- Isolation: additive — a brand-new schema, touches NO research tables. Reversible
--            with `DROP SCHEMA api CASCADE;`.
-- ============================================================================
--
-- The lnhistory API authenticates researchers by API key and meters/limits their
-- usage by a cost-weighted daily budget. This schema is the durable store; live
-- enforcement is in-memory in the API process, with an async flush to api.usage.
--
-- Reader roles (ai_reader, grafanareader) are intentionally NOT granted access —
-- api.api_keys holds key hashes. If a least-privilege API role is introduced later
-- (instead of admin), grant it: USAGE ON SCHEMA api, and SELECT/INSERT/UPDATE on
-- these three tables.
-- ============================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS api AUTHORIZATION admin;

-- --- keys ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api.api_keys (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_hash         char(64)    NOT NULL UNIQUE,          -- sha256(raw key), hex
    display_prefix   varchar(16) NOT NULL,                 -- non-secret, e.g. 'lnh_ab12cd'
    role             text        NOT NULL DEFAULT 'researcher'
                       CHECK (role IN ('admin','researcher')),
    owner_label      text        NOT NULL,                 -- who this key belongs to
    daily_budget     integer,                              -- NULL => global default
    burst_per_sec    integer,                              -- NULL => global default
    max_stream_conns integer,                              -- NULL => global default
    expires_at       timestamptz,                          -- NULL => never
    enabled          boolean     NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now(),
    last_used_at     timestamptz
);

-- --- admin-tunable endpoint cost weights -----------------------------------
CREATE TABLE IF NOT EXISTS api.endpoint_weights (
    route_key   text    PRIMARY KEY,                       -- stable key from [ResourceCost]
    weight      integer NOT NULL CHECK (weight >= 0),
    description text
);

-- --- aggregated usage ledger (async-flushed; NO identity => no sequence risk) --
CREATE TABLE IF NOT EXISTS api.usage (
    key_id          bigint  NOT NULL REFERENCES api.api_keys(id) ON DELETE CASCADE,
    usage_day       date    NOT NULL,                      -- UTC day (app supplies it)
    endpoint        text    NOT NULL,                      -- route_key
    sum_cost        bigint  NOT NULL DEFAULT 0,
    req_count       bigint  NOT NULL DEFAULT 0,
    sum_duration_ms bigint  NOT NULL DEFAULT 0,
    sum_bytes       bigint  NOT NULL DEFAULT 0,
    PRIMARY KEY (key_id, usage_day, endpoint)
);
CREATE INDEX IF NOT EXISTS idx_api_usage_day ON api.usage (usage_day);

